	/**
	 * راهنمای یک گزینه.
	 *
	 * @param string $group نام گروه.
	 * @param string $key   نام گزینه.
	 * @return string رشته‌ی خالی اگر راهنما نداشته باشد.
	 */
	public static function field( $group, $key ) {
		$fields = self::fields();

		return (string) ( $fields[ $group ][ $key ] ?? '' );
	}

	/**
	 * راهنمای یک بخش.
	 *
	 * @param string $key نام بخش.
	 * @return array|null
	 */
	public static function section( $key ) {
		$sections = self::sections();

		return $sections[ $key ] ?? null;
	}

	/**
	 * چاپ جعبه‌ی راهنمای یک بخش.
	 *
	 * @param string $key  نام بخش.
	 * @param bool   $open آیا پیش‌فرض باز باشد.
	 * @return void
	 */
	public static function render( $key, $open = false ) {
		$section = self::section( $key );

		if ( ! $section ) {
			return;
		}
		?>
		<details class="ky-guide" <?php echo $open ? 'open' : ''; ?>>
			<summary>
				<span class="ky-guide-icon">💡</span>
				<?php echo esc_html( $section['title'] ); ?>
			</summary>
			<div class="ky-guide-body">
				<p><?php echo esc_html( $section['intro'] ); ?></p>

				<?php if ( ! empty( $section['steps'] ) ) : ?>
					<ol>
						<?php foreach ( $section['steps'] as $step ) : ?>
							<li><?php echo esc_html( $step ); ?></li>
						<?php endforeach; ?>
					</ol>
				<?php endif; ?>

				<?php if ( ! empty( $section['notes'] ) ) : ?>
					<ul class="ky-guide-notes">
						<?php foreach ( $section['notes'] as $note ) : ?>
							<li><?php echo esc_html( $note ); ?></li>
						<?php endforeach; ?>
					</ul>
				<?php endif; ?>
			</div>
		</details>
		<?php
	}

	/**
	 * چاپ راهنمای یک گزینه، زیر همان فیلد.
	 *
	 * @param string $group نام گروه.
	 * @param string $key   نام گزینه.
	 * @param string $tag   تگ دربرگیرنده.
	 * @return void
	 */
	public static function hint( $group, $key, $tag = 'small' ) {
		$text = self::field( $group, $key );

		if ( '' === $text ) {
			return;
		}

		printf(
			'<%1$s class="ky-hint">%2$s</%1$s>',
			esc_html( $tag ),
			esc_html( $text )
		);
	}
